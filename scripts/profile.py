#!/usr/bin/env python3
"""Sampling profile of the native engine without perf or root.

Copies rust/ to a scratch directory, adds a SIGPROF handler that records the instruction pointer and the current
stage (the number of stage log lines printed so far), builds with line tables, runs a dataset, and prints the hottest
lines per stage via addr2line.

Usage: profile.py DATA_DIR [WORKDIR]      (needs cargo, addr2line, network for the libc crate once)
"""
import collections
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PROF = r'''
// ---- scratch sampling profiler (generated by scripts/profile.py)
use std::sync::atomic::{AtomicU64, AtomicUsize, Ordering as O};
static SAMPLES: [AtomicU64; 1 << 21] = [const { AtomicU64::new(0) }; 1 << 21];
static NS: AtomicUsize = AtomicUsize::new(0);
static STAGE: AtomicU64 = AtomicU64::new(0);
extern "C" fn on_prof(_sig: i32, _info: *mut libc::siginfo_t, ctx: *mut libc::c_void) {
    unsafe {
        let uc = ctx as *mut libc::ucontext_t;
        let rip = (*uc).uc_mcontext.gregs[libc::REG_RIP as usize] as u64;
        let i = NS.fetch_add(1, O::Relaxed);
        if i < SAMPLES.len() {
            SAMPLES[i].store(rip | (STAGE.load(O::Relaxed) << 56), O::Relaxed);
        }
    }
}
fn prof_start() {
    unsafe {
        let mut sa: libc::sigaction = std::mem::zeroed();
        sa.sa_sigaction = on_prof as usize;
        sa.sa_flags = libc::SA_SIGINFO | libc::SA_RESTART;
        libc::sigaction(libc::SIGPROF, &sa, std::ptr::null_mut());
        let tv = libc::timeval { tv_sec: 0, tv_usec: 1000 };
        let it = libc::itimerval { it_interval: tv, it_value: tv };
        libc::setitimer(libc::ITIMER_PROF, &it, std::ptr::null_mut());
    }
}
fn prof_dump() {
    let maps = std::fs::read_to_string("/proc/self/maps").unwrap_or_default();
    let exe = std::env::current_exe().unwrap();
    let base = maps.lines().find(|l| l.ends_with(exe.to_str().unwrap())).and_then(|l| l.split('-').next()).unwrap_or("0");
    let mut out = format!("base {base}\n");
    let n = NS.load(O::Relaxed).min(SAMPLES.len());
    for i in 0..n {
        let v = SAMPLES[i].load(O::Relaxed);
        out.push_str(&format!("{} {:x}\n", v >> 56, v & ((1u64 << 56) - 1)));
    }
    std::fs::write(std::env::var("PROF_OUT").unwrap(), out).unwrap();
}
'''


def build(work: Path) -> Path:
    src = work / "src"
    src.mkdir(parents=True, exist_ok=True)
    shutil.copy(ROOT / "rust" / "Cargo.lock", work / "Cargo.lock")
    toml = (ROOT / "rust" / "Cargo.toml").read_text().replace("[dependencies]", '[dependencies]\nlibc = "0.2"')
    (work / "Cargo.toml").write_text(toml)
    s = (ROOT / "rust" / "src" / "main.rs").read_text()
    s = s.replace("struct Logger(Instant);", PROF + "\nstruct Logger(Instant);", 1)
    s = s.replace("    fn log(&self, what: &str) {\n", "    fn log(&self, what: &str) {\n        STAGE.fetch_add(1, O::Relaxed);\n", 1)
    s = s.replace("    let lg = Logger(Instant::now());", "    prof_start();\n    let lg = Logger(Instant::now());", 1)
    s = s.replace('    lg.log("done");', '    lg.log("done");\n    prof_dump();', 1)
    (src / "main.rs").write_text(s)
    env = dict(os.environ, CARGO_PROFILE_RELEASE_DEBUG="line-tables-only")
    cargo = shutil.which("cargo") or os.path.expanduser("~/.cargo/bin/cargo")
    subprocess.run([cargo, "build", "--release"], cwd=work, env=env, check=True, capture_output=True)
    return work / "target" / "release" / "ss"


def main():
    data = sys.argv[1]
    work = Path(sys.argv[2] if len(sys.argv) > 2 else tempfile.mkdtemp(prefix="ssprof-"))
    exe = build(work)
    out_dir = work / "out"
    shutil.rmtree(out_dir, ignore_errors=True)
    samples_file = work / "samples.txt"
    env = dict(os.environ, DATA_DIR=data, OUTPUT_DIR=str(out_dir), NCPU="8", PROF_OUT=str(samples_file))
    p = subprocess.run([str(exe)], env=env, capture_output=True, text=True)
    stage_names = [re.sub(r"^\[[^\]]*\]\s*", "", l).strip() for l in p.stderr.splitlines()]
    lines = samples_file.read_text().split("\n")
    base = int(lines[0].split()[1], 16)
    samples = [(int(a), int(b, 16) - base) for a, b in (l.split() for l in lines[1:] if l)]
    addrs = sorted({o for _, o in samples})
    out = subprocess.run(["addr2line", "-e", str(exe), "-a", "-f", "-i", "-C"] + [hex(a) for a in addrs],
                         capture_output=True, text=True).stdout.split("\n")
    sym, cur, frames, pend = {}, None, [], None
    for l in out:
        if re.fullmatch(r"0x[0-9a-f]+", l):
            if cur is not None:
                sym[cur] = frames
            cur, frames, pend = int(l, 16), [], None
        elif l:
            if pend is None:
                pend = l
            else:
                frames.append((pend, l))
                pend = None
    if cur is not None:
        sym[cur] = frames
    per = collections.defaultdict(collections.Counter)
    tot = collections.Counter()
    for st, o in samples:
        fr = sym.get(o) or [("??", "??")]
        fn = re.sub(r"<[^<>]*>", "", fr[0][0])[:60]
        line = next((f[1].split("/")[-1] for f in fr if "main.rs" in f[1]), fr[0][1].split("/")[-1])
        per[st][(fn, line)] += 1
        tot[st] += 1
    n = len(samples)
    print(f"{n} samples (~{n * 0.004:.1f} CPU-s at 4 ms/sample); work dir {work}")
    for st in sorted(tot):
        name = stage_names[st] if st < len(stage_names) else "(after last log)"
        print(f"\n=== {name}: {tot[st]} samples = {100 * tot[st] / n:.1f}%")
        for (fn, line), c in per[st].most_common(6):
            print(f"  {100 * c / tot[st]:5.1f}%  {fn:60s} {line}")


if __name__ == "__main__":
    main()
